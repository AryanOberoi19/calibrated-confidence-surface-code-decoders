"""A5: statistical baselines against Learn-then-Test on the committed splits (arXiv v1 plan, task A5).

Every cell M4 covers (r != 13; same scores, Train thresholds, Calibrate and Test shots, alphas, delta). Rules:
  ltt         fixed-sequence Learn-then-Test, exact binomial p-values (the method of the report)
  bonferroni  every threshold from the start tested at delta / m; loosest certified
  sgr         Geifman and El-Yaniv selection with guaranteed risk (binary search, delta / ceil(log2 m) per step)
  ltt_hb      fixed sequence with Hoeffding-Bentkus p-values
  plugin      uncertified reference (loosest threshold with Calibrate error <= alpha)
Validity of the certified rules over calibration draws is checked by scripts/p3_validity.py (Part 1).
Conformal risk control is not compared: it bounds an expectation, and its natural loss here controls the joint
rate P(kept and wrong), not the rate among kept shots.

Writes results/p4_baselines.csv and results/p4_baselines.md.
"""
import csv
import pathlib

import numpy as np

from qeccal.calibration import score_from_q
from qeccal.data import list_experiments, split_indices
from qeccal.guarantees import KEEP_GRID, bonferroni, cp_lower, learn_then_test, loosest_where, ltt_hb, sgr, thresholds
from qeccal.soft.cache import cache_path, load

REPO = pathlib.Path(__file__).resolve().parents[1]
RES = REPO / "results"
ALPHAS = (1e-3, 3e-3, 1e-2, 3e-2, 1e-1)
DELTA = 0.05
COMBOS = [("mwpm_gap", "si1000"), ("mwpm_gap", "rl"), ("exact", "si1000"), ("exact", "rl"), ("bm_gap", "rl"), ("nn", "rl")]
RULES = ("ltt", "bonferroni", "sgr", "ltt_hb", "plugin")
FIELDS = ["key", "distance", "patch", "basis", "rounds", "method", "prior", "alpha", "rule", "keep", "cal_n",
          "cal_errors", "test_n", "test_errors", "test_rate", "kept_frac", "exceed", "sig_exceed"]


def run(e):
    idx = split_indices(e)
    obs = e.observable_flips()
    base = {"key": e.key, "distance": e.distance, "patch": e.patch, "basis": e.basis, "rounds": e.rounds}
    rows = []
    for method, prior in COMBOS:
        if not cache_path(method, prior, e.key).exists():
            continue
        o = load(method, prior, e.key)
        s = o["gap"].astype(np.float64) if "gap" in o else score_from_q(o["q"])
        wrong = o["pred"] != obs
        tr, ca, te = idx["train"], idx["calibrate"], idx["test"]
        if "fit_mask" in o:
            tr = tr[~o["fit_mask"][tr]]
        lams = thresholds(s[tr])
        s_ca, w_ca, s_te, w_te = s[ca], wrong[ca], s[te], wrong[te]
        cal_err = [w_ca[s_ca >= lam].mean() if (s_ca >= lam).any() else np.inf for lam in lams]
        for alpha in ALPHAS:
            choice = {"ltt": learn_then_test(s_ca, w_ca, lams, alpha, DELTA)[0],
                      "bonferroni": bonferroni(s_ca, w_ca, lams, alpha, DELTA),
                      "sgr": sgr(s_ca, w_ca, lams, alpha, DELTA),
                      "ltt_hb": ltt_hb(s_ca, w_ca, lams, alpha, DELTA),
                      "plugin": loosest_where(cal_err, lambda v: v <= alpha)}
            for rule in RULES:
                i = choice[rule]
                row = {**base, "method": method, "prior": prior, "alpha": alpha, "rule": rule}
                if i is None:
                    rows.append({**row, **{f: "" for f in FIELDS if f not in row}})
                    continue
                kc, kt = s_ca >= lams[i], s_te >= lams[i]
                n, er = int(kt.sum()), int(w_te[kt].sum())
                rows.append({**row, "keep": KEEP_GRID[i], "cal_n": int(kc.sum()), "cal_errors": int(w_ca[kc].sum()),
                             "test_n": n, "test_errors": er, "test_rate": er / n if n else "", "kept_frac": n / te.size,
                             "exceed": int(n > 0 and er / n > alpha), "sig_exceed": int(cp_lower(er, n) > alpha)})
    return rows


def main():
    import pandas as pd
    rows = [r for e in list_experiments() if e.rounds != 13 for r in run(e)]
    with (RES / "p4_baselines.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    df = pd.DataFrame(rows)
    for c in ("kept_frac", "exceed", "sig_exceed"):
        df[c] = pd.to_numeric(df[c])
    df["sel"] = df["keep"] != ""
    m4 = pd.read_csv(RES / "m4_guarantees.csv")
    a = df[df.rule.isin(["ltt", "plugin"])].copy()
    b = m4[m4.rule.isin(["ltt", "plugin"])]
    same = (a[["key", "method", "prior", "alpha", "rule", "test_n", "test_errors"]].fillna("").astype(str).reset_index(drop=True)
            .equals(b[["key", "method", "prior", "alpha", "rule", "test_n", "test_errors"]].fillna("").astype(str)
                    .apply(lambda s: s.str.replace(r"\.0$", "", regex=True)).reset_index(drop=True)))
    L = ["# A5: statistical baselines (committed splits)", "",
         "Generated by `scripts/p4_baselines.py`. All certified rules share Learn-then-Test's start rule; delta = 0.05. "
         "Certified = the rule selected a threshold. Exceeds / significant: share of certified experiments whose Test "
         "error among kept shots is above alpha / whose one-sided 95% Clopper-Pearson lower bound is. Kept = mean "
         "fraction of Test shots kept, over certified experiments. Kept vs LTT = mean of (rule kept - LTT kept) over "
         "experiments where both certify. Validity over calibration draws: `results/p3_validity.md`, Part 1.", "",
         f"Check: ltt and plugin rows reproduce `results/m4_guarantees.csv` (Test counts): {'yes' if same else 'NO'}.", ""]
    for (m, p) in COMBOS:
        v = df[(df.method == m) & (df.prior == p)]
        if v.empty:
            continue
        L += [f"## {m} / {p} ({v.key.nunique()} experiments)", "",
              "| alpha | rule | certified | exceeds | significant | kept | kept vs LTT |", "|---|---|---|---|---|---|---|"]
        for al in ALPHAS:
            lt = v[(v.alpha == al) & (v.rule == "ltt") & v.sel].set_index("key").kept_frac
            for r in RULES:
                x = v[(v.alpha == al) & (v.rule == r)]
                s_ = x[x.sel]
                k = s_.set_index("key").kept_frac
                both = lt.index.intersection(k.index)
                dk = f"{(k[both] - lt[both]).mean():+.3f} ({len(both)})" if len(both) and r != "ltt" else "-"
                L.append(f"| {al:g} | {r} | {len(s_)}/{len(x)} | "
                         + (f"{100 * s_.exceed.mean():.1f}% | {100 * s_.sig_exceed.mean():.1f}% | {s_.kept_frac.mean():.3f} | {dk} |"
                            if len(s_) else "- | - | - | - |"))
        L.append("")
    (RES / "p4_baselines.md").write_text("\n".join(L))
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main()
