"""Summarise M6: early abort learned by Q-iteration and certified by Learn-then-Test (spec section 8.8).

    python scripts/m6_summary.py
Reads results/m6_early_abort.csv, m6_policies.csv, m6_qcheck.csv and the prefix and soft caches; writes
results/m6_summary.md, results/m6_gain.png and results/m6_policy.png.
"""
import json
import pathlib

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from qeccal import plotting  # noqa: E402
from qeccal.data import list_experiments, split_indices  # noqa: E402
from qeccal.data.willow import get_experiment  # noqa: E402
from qeccal.soft.cache import load  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parents[1]
RES = REPO / "results"
PREFIX = RES / "cache" / "prefix" / "rl"
EXAMPLE, EXAMPLE_ALPHA = "d3_at_q4_5/Z/r50", 0.1
RULES = ("static", "final_only", "early_abort")


def fmt_a(a):
    return {1e-3: "1e-3", 3e-3: "3e-3", 1e-2: "1e-2", 3e-2: "3e-2", 1e-1: "1e-1"}.get(a, f"{a:g}")


def informativeness():
    """Per (d, r): how well the prefix gap at mid-run predicts being kept by a top-20% final-gap rule (Test shots)."""
    rows = []
    for e in list_experiments(rounds=(10, 30, 50)):
        z = np.load(PREFIX / (e.key.replace("/", "__") + ".npz"))
        te = split_indices(e)["test"]
        s = load("mwpm_gap", "rl", e.key)["gap"][te]
        j = len(z["checkpoints"]) // 2
        g = z["gaps"][te, j]
        kept = s >= np.quantile(s, 0.8)
        low = g <= np.quantile(g, 0.2)
        rows.append({"distance": e.distance, "rounds": e.rounds, "t": int(z["checkpoints"][j]),
                     "spearman": pd.Series(g).rank().corr(pd.Series(s).rank()),
                     "lift": kept[low].mean() / kept.mean()})
    return pd.DataFrame(rows).groupby(["distance", "rounds"]).agg(t=("t", "first"), spearman=("spearman", "mean"),
                                                                  lift=("lift", "mean")).reset_index()


def main():
    df = pd.read_csv(RES / "m6_early_abort.csv")
    pol = pd.read_csv(RES / "m6_policies.csv")
    qc = pd.read_csv(RES / "m6_qcheck.csv")
    n_exp = df.key.nunique()
    L = ["# M6 early abort (generated by scripts/m6_summary.py)", "",
         "Score: MWPM gap and prefix gap, RL prior. Policy family learned on Train (Q-iteration, Dinkelbach on kept shots "
         "per round), Learn-then-Test on Calibrate (delta = 0.05), evaluated on Test. "
         f"{n_exp} experiments (r = 10, 30, 50). Uncertified experiments keep nothing. "
         "Per-experiment rows: `results/m6_early_abort.csv`; certified policies: `results/m6_policies.csv`.", ""]

    # --- guarantee ---------------------------------------------------------------------------------------------
    c = df[df.certified == 1]
    L += ["## Does the certificate hold on Test?", "",
          "| Rule | Certified (experiment, alpha) cells | Exceed alpha | Significantly exceed |", "|---|---|---|---|"]
    for r in RULES:
        x = c[c.rule == r]
        L.append(f"| {r} | {len(x)} | {int(x.exceed.sum())} ({100 * x.exceed.mean():.1f}%) | "
                 f"{int(x.sig_exceed.sum())} ({100 * x.sig_exceed.mean():.1f}%) |")
    L += ["", "Significant: one-sided 95% Clopper-Pearson lower bound above alpha. Cells sharing an experiment are not "
          "independent.", ""]

    # --- throughput ---------------------------------------------------------------------------------------------
    piv = df.pivot_table(index=["key", "distance", "rounds", "alpha"], columns="rule",
                         values=["throughput", "certified", "keep", "aborted", "rounds_mean"]).reset_index()
    L += ["## Kept shots per round of hardware time", "",
          "Throughput = kept Test shots / rounds used by all attempted Test shots. Ratios are medians over experiments "
          "where both rules certify. E: early abort, F: final-only ablation (same keep thresholds, never aborts), "
          "S: static rule of M4 (5% keep grid).", "",
          "| d | r | alpha | Certified S / F / E (of n) | E / S | E / F | Aborted early | Rounds per attempt | Kept S / E |",
          "|---|---|---|---|---|---|---|---|---|"]
    gains = []
    for (d, rr, a), g in piv.groupby([("distance", ""), ("rounds", ""), ("alpha", "")]):
        cs, cf_, ce = (int(g[("certified", r)].sum()) for r in RULES)
        if cs + cf_ + ce == 0:
            continue
        both_s = g[(g[("certified", "static")] == 1) & (g[("certified", "early_abort")] == 1)]
        both_f = g[(g[("certified", "final_only")] == 1) & (g[("certified", "early_abort")] == 1)]
        es = (both_s[("throughput", "early_abort")] / both_s[("throughput", "static")]).median() if len(both_s) else np.nan
        ef = (both_f[("throughput", "early_abort")] / both_f[("throughput", "final_only")]).median() if len(both_f) else np.nan
        e_c = g[g[("certified", "early_abort")] == 1]
        ab = e_c[("aborted", "early_abort")].mean() if len(e_c) else np.nan
        rm = e_c[("rounds_mean", "early_abort")].mean() if len(e_c) else np.nan
        ks = g[g[("certified", "static")] == 1][("keep", "static")].mean() if cs else np.nan
        ke = e_c[("keep", "early_abort")].mean() if len(e_c) else np.nan
        L.append(f"| {d} | {rr} | {fmt_a(a)} | {cs} / {cf_} / {ce} (of {len(g)}) | {es:.2f} | {ef:.2f} | "
                 f"{100 * ab:.0f}% | {rm:.1f} of {rr} | {100 * ks:.1f}% / {100 * ke:.1f}% |".replace("nan%", "-")
                 .replace("| nan |", "| - |").replace("nan of", "- of"))
        for _, row in both_s.iterrows():
            gains.append({"d": d, "r": rr, "alpha": a, "es": row[("throughput", "early_abort")] / row[("throughput", "static")],
                          "ef": (row[("throughput", "early_abort")] / row[("throughput", "final_only")]
                                 if row[("certified", "final_only")] == 1 else np.nan)})
    gains = pd.DataFrame(gains)
    only_e = piv[(piv[("certified", "early_abort")] == 1) & (piv[("certified", "static")] == 0)]
    only_s = piv[(piv[("certified", "early_abort")] == 0) & (piv[("certified", "static")] == 1)]
    L += ["", f"Certified by early abort but not by the static rule: {len(only_e)} (experiment, alpha) cells; "
          f"the reverse: {len(only_s)}.", ""]

    # --- Q-learning check -----------------------------------------------------------------------------------------
    L += ["## Q-learning check", "",
          f"For every experiment, the batch Q-table (one backward sweep) was recomputed by sample-by-sample Q-learning "
          f"with a target table refreshed every epoch: largest difference {qc.max_abs_diff.max():.1e}; identical "
          f"decisions in {int(qc.same_decisions.sum())} of {len(qc)} experiments.", ""]

    # --- why the gain depends on distance ------------------------------------------------------------------------
    info = informativeness()
    L += ["## How much the prefix says about the final decision", "",
          "Test shots, mid-run checkpoint. Spearman: rank correlation between the prefix gap and the final gap. Lift: "
          "how often a shot in the lowest fifth of prefix gaps is kept by a top-20% final-gap rule, relative to the "
          "average shot (0 = never kept, 1 = no information).", "",
          "| d | r | Checkpoint round | Spearman | Lift |", "|---|---|---|---|---|"]
    for _, r in info.iterrows():
        L.append(f"| {int(r.distance)} | {int(r.rounds)} | {int(r.t)} | {r.spearman:.2f} | {r.lift:.2f} |")
    (RES / "m6_summary.md").write_text("\n".join(L) + "\n")

    # --- figures ----------------------------------------------------------------------------------------------------
    plotting.apply()
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 2.7), gridspec_kw={"width_ratios": [1.6, 1]})
    ax = axes[0]
    cfgs = [(d, r) for d in (3, 5, 7) for r in (10, 30, 50)]
    for i, a in enumerate((1e-2, 3e-2, 1e-1)):
        for x, (d, r) in enumerate(cfgs):
            v = gains[(gains.d == d) & (gains.r == r) & (gains.alpha == a)].ef.dropna()
            if len(v):
                xx = x + (i - 1) * 0.22
                ax.plot([xx, xx], [v.min(), v.max()], color=plotting.C[i], lw=1.0, alpha=0.6)
                ax.plot(xx, v.median(), plotting.MK[i], color=plotting.C[i], label=f"alpha = {fmt_a(a)}" if x == 0 or
                        not any(l.get_label() == f"alpha = {fmt_a(a)}" for l in ax.lines) else None)
    ax.axhline(1, color=plotting.MUTED, lw=0.8)
    ax.set_xticks(range(len(cfgs)), [f"d={d}\nr={r}" for d, r in cfgs])
    ax.set_ylabel("kept shots per round,\nearly abort / no abort")
    ax.set_title("What aborting adds at the same certified alpha")
    ax.legend(loc="upper right")
    ax = axes[1]
    for i, d in enumerate((3, 5, 7)):
        x = info[info.distance == d]
        ax.plot(x.rounds, x.lift, plotting.MK[i] + "-", color=plotting.C[i], label=f"d = {d}")
    ax.set_xlabel("rounds r")
    ax.set_ylabel("lift (1 = no information)")
    ax.set_ylim(0, 1)
    ax.set_title("Does a low prefix gap flag a doomed shot?")
    ax.legend(loc="lower right")
    fig.tight_layout()
    fig.savefig(RES / "m6_gain.png")
    plt.close(fig)

    # example policy
    p = pol[(pol.key == EXAMPLE) & (np.isclose(pol.alpha, EXAMPLE_ALPHA))].iloc[0]
    row = df[(df.key == EXAMPLE) & np.isclose(df.alpha, EXAMPLE_ALPHA)].set_index("rule")
    cps = json.loads(p.checkpoints)
    share = np.array(json.loads(p.abort_share_test))
    below = [np.nan if v is None else v for v in json.loads(p.abort_below)]
    e = get_experiment(EXAMPLE)
    te = split_indices(e)["test"]
    z = np.load(PREFIX / (EXAMPLE.replace("/", "__") + ".npz"))
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 2.7))
    ax = axes[0]
    xs = [0] + [t for t in cps for _ in (0, 1)] + [e.rounds]
    alive = 1 - np.concatenate([[0], np.cumsum(share)])
    ys = [1] + [v for k in range(len(cps)) for v in (alive[k], alive[k + 1])] + [alive[-1]]
    ax.plot(xs, ys, color=plotting.C[0], label="early abort: still running")
    ax.plot([0, e.rounds], [1, 1], color=plotting.C[1], label="static: still running")
    ax.plot([e.rounds], [row.loc["early_abort", "keep"]], "o", color=plotting.C[0])
    ax.plot([e.rounds], [row.loc["static", "keep"]], "s", color=plotting.C[1])
    ax.annotate(f"kept {100 * row.loc['early_abort', 'keep']:.0f}%", (e.rounds, row.loc["early_abort", "keep"]),
                xytext=(7, -7), textcoords="offset points", color=plotting.C[0], fontsize=7.5)
    ax.annotate(f"kept {100 * row.loc['static', 'keep']:.0f}%", (e.rounds, row.loc["static", "keep"]),
                xytext=(7, 1), textcoords="offset points", color=plotting.C[1], fontsize=7.5)
    ax.set_xlim(-2, 64)
    ax.set_xticks(range(0, e.rounds + 1, 10))
    ax.set_xlabel("round")
    ax.set_ylabel("share of Test shots")
    ax.set_ylim(0, 1.05)
    ax.set_title(f"{EXAMPLE}, alpha = {fmt_a(EXAMPLE_ALPHA)}")
    ax.legend(loc="lower left", fontsize=7.5)
    ax = axes[1]
    g = z["gaps"][te]
    q = np.quantile(g, [0.25, 0.5, 0.75], axis=0)
    ax.fill_between(cps, q[0], q[2], color=plotting.C[0], alpha=0.15, lw=0, label="prefix gap, middle half")
    ax.plot(cps, q[1], color=plotting.C[0], lw=1.0, label="prefix gap, median")
    ax.plot(cps, below, "s-", color=plotting.C[1], label="abort below")
    ax.set_xlabel("checkpoint round")
    ax.set_ylabel("prefix gap")
    ax.set_title("The learned abort rule")
    ax.legend(loc="upper right", fontsize=7.5)
    fig.tight_layout()
    fig.savefig(RES / "m6_policy.png")
    plt.close(fig)
    print("\n".join(L))


if __name__ == "__main__":
    main()
