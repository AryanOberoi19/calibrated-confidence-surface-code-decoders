"""A2 follow-up (post hoc, descriptive): is the file-order structure found in A2 a step between initialization
bitstrings rather than drift in time?

The dataset paper (arXiv:2408.13687, supplementary section V.2) describes each experiment as "50,000 repetitions
(10 initialization bitstrings times 5,000 repetitions)". In every one of the 420 files the shots come as 10
contiguous blocks of 5,000, one bitstring per block (sweep_bits.b8). A2's 50 blocks of 1,000 shots nest inside
these, so A2 cannot tell a step between bitstrings from drift within one.

Per experiment, for x1 (detection events per shot) and x2 (MWPM error indicator, RL prior):
  between  block_variance_ratio over the 10 bitstring blocks (1 = no excess)
  within   mean over the 10 blocks of block_variance_ratio over 5 sub-blocks of 1,000 shots inside the block
  p_within permutation p-value for "sub-block means vary within bitstring blocks more than a random order
           inside each block would give": statistic = sum over blocks of the variance of its 5 sub-block
           means; shots permuted within their own block; 1,000 permutations
Seeds: np.random.default_rng([20261117, 11, experiment index]).
Aggregate: experiments with p_within < 0.05 (21 of 420 expected), Benjamini-Hochberg count, median ratios.
Read this as a decomposition of A2's result; it changes no A2 test or rule.

    python scripts/p1b_bitstring_blocks.py [--workers 4]      # resumable: results/cache/p1b/
Writes results/p1b_bitstring_blocks.csv and results/p1b_bitstring_blocks.md.
"""
import argparse
import concurrent.futures as cf
import json
import pathlib

import numpy as np
from scipy.stats import binom

from qeccal.data import list_experiments, read_b8
from qeccal.diagnostics import block_variance_ratio
from qeccal.soft.cache import load

REPO = pathlib.Path(__file__).resolve().parents[1]
RES = REPO / "results"
CACHE = RES / "cache" / "p1b"
N_SUB, N_PERM = 5, 1000
POP = np.array([bin(i).count("1") for i in range(256)], np.uint8)


def within_stat(x, starts, size):
    blocks = np.stack([x[s:s + size] for s in starts])                       # (10, 5000)
    m = blocks.reshape(len(starts), N_SUB, size // N_SUB).mean(axis=2)
    return float(m.var(axis=1).sum())


def p_within(x, starts, size, rng):
    blocks = np.stack([x[s:s + size] for s in starts]).astype(np.float64)
    obs = blocks.reshape(len(starts), N_SUB, -1).mean(axis=2).var(axis=1).sum()
    hits = 0
    for _ in range(N_PERM // 100):
        p = rng.permuted(np.broadcast_to(blocks, (100,) + blocks.shape), axis=2)
        s = p.reshape(100, len(starts), N_SUB, -1).mean(axis=3).var(axis=2).sum(axis=1)
        hits += int((s >= obs - 1e-12 * max(obs, 1e-300)).sum())
    return (1 + hits) / (1 + N_PERM)


def run(job):
    i, e = job
    out = CACHE / (e.key.replace("/", "__") + ".json")
    if out.exists():
        return
    sw = read_b8(e.path / "sweep_bits.b8", e.circuit().num_sweep_bits)
    _, code = np.unique(sw, axis=0, return_inverse=True)
    code = code.ravel()
    starts = np.flatnonzero(np.r_[True, code[1:] != code[:-1]])
    size = e.shots // len(starts)
    assert len(starts) == 10 and np.all(np.diff(np.r_[starts, e.shots]) == size), e.key
    x1 = POP[e.detection_events(packed=True)].sum(axis=1, dtype=np.int64)
    x2 = load("mwpm_gap", "rl", e.key)["pred"] != e.observable_flips()
    rng = np.random.default_rng([20261117, 11, i])
    row = {"index": i, "key": e.key, "distance": e.distance, "rounds": e.rounds, "distinct_bitstrings": int(len(np.unique(code)))}
    for name, x in (("x1", x1), ("x2", x2)):
        row[f"between_{name}"] = block_variance_ratio(x, 10)
        row[f"within_{name}"] = float(np.nanmean([block_variance_ratio(x[s:s + size], N_SUB) for s in starts]))
        row[f"p_within_{name}"] = p_within(x, starts, size, rng)
    tmp = out.with_suffix(".tmp")
    tmp.write_text(json.dumps(row))
    tmp.rename(out)


def bh_count(p, q=0.05):
    p = np.sort(np.asarray(p))
    ok = np.flatnonzero(p <= q * np.arange(1, p.size + 1) / p.size)
    return int(ok[-1] + 1) if ok.size else 0


def summarize(n_total):
    import pandas as pd
    df = pd.DataFrame([json.loads(f.read_text()) for f in CACHE.glob("*.json")]).sort_values("index")
    assert len(df) == n_total
    df.to_csv(RES / "p1b_bitstring_blocks.csv", index=False)
    a2 = pd.read_csv(RES / "p1_shot_order.csv").set_index("key")
    n = len(df)
    L = ["# A2 follow-up: initialization-bitstring blocks (post hoc, descriptive)", "",
         "Generated by `scripts/p1b_bitstring_blocks.py`. Every file holds 10 contiguous blocks of 5,000 shots, one "
         f"initialization bitstring each ({int((df.distinct_bitstrings == 10).sum())} files with 10 distinct bitstrings, "
         f"{int((df.distinct_bitstrings < 10).sum())} with fewer, a bitstring repeating in two blocks). Ratios: 1 = no "
         "excess over a random order. A2's ratio uses 50 blocks of 1,000 shots across the whole file.", "",
         "| | A2 ratio (50 blocks), median | between bitstring blocks, median | within blocks, median | within-block p < 0.05 | BH 5% |",
         "|---|---|---|---|---|---|"]
    for x, lab in (("x1", "detection events per shot"), ("x2", "decoder error (MWPM, RL prior)")):
        k = int((df[f"p_within_{x}"] < 0.05).sum())
        L.append(f"| {lab} | {a2.loc[df.key, f'ratio_{x}'].median():.2f} | {df[f'between_{x}'].median():.2f} | "
                 f"{df[f'within_{x}'].median():.2f} | {k} of {n} (binomial p {binom.sf(k - 1, n, 0.05):.2g}) | "
                 f"{bh_count(df[f'p_within_{x}'].values)} |")
    g = df.groupby("rounds")
    L += ["", f"Expected under no within-block structure: {0.05 * n:.0f} of {n} below 0.05.", "",
          "## By round count (medians; counts of within-block p < 0.05)", "",
          "| rounds | between x1 | within x1 | within p<0.05 x1 | between x2 | within x2 | within p<0.05 x2 |",
          "|---|---|---|---|---|---|---|"]
    for r, v in g:
        L.append(f"| {r} | {v.between_x1.median():.2f} | {v.within_x1.median():.2f} | {int((v.p_within_x1 < 0.05).sum())}/{len(v)} | "
                 f"{v.between_x2.median():.2f} | {v.within_x2.median():.2f} | {int((v.p_within_x2 < 0.05).sum())}/{len(v)} |")
    (RES / "p1b_bitstring_blocks.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()
    CACHE.mkdir(parents=True, exist_ok=True)
    exps = list_experiments()
    jobs = [(i, e) for i, e in enumerate(exps) if not (CACHE / (e.key.replace("/", "__") + ".json")).exists()]
    print(f"{len(exps) - len(jobs)} of {len(exps)} done; running {len(jobs)}", flush=True)
    with cf.ProcessPoolExecutor(max_workers=args.workers) as pool:
        list(pool.map(run, jobs))
    summarize(len(exps))


if __name__ == "__main__":
    main()
