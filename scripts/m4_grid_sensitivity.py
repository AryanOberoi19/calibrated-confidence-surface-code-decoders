"""Sensitivity of the Learn-then-Test results to the threshold grid (report, item 8 of the October 2026 revision).

The main run (scripts/m4_calibrate_certify.py) uses a grid of keep fractions k = 5%, 10%, ..., 100% of Train shots.
The headline "price of the certificate" (Learn-then-Test against the plug-in rule) is 2-3 percentage points of kept
shots, which is smaller than one grid step. This script reruns Learn-then-Test and the plug-in rule on the same frozen
scores and the same splits with 5%, 2% and 1% steps, so the price can be read off at finer resolution. Nothing else
changes: thresholds are Train quantiles, the start of the fixed sequence follows qeccal.guarantees.start_keep on the
chosen grid, delta = 0.05.

    python scripts/m4_grid_sensitivity.py
Writes results/m4_grid_sensitivity.csv (one row per experiment, score, grid, alpha and rule) and
results/m4_grid_sensitivity.md. The 5% rows reproduce results/m4_guarantees.csv.
"""
import argparse
import concurrent.futures as cf
import csv
import pathlib
import time

import numpy as np

from qeccal.calibration import score_from_q
from qeccal.data import list_experiments, split_indices
from qeccal.data.willow import get_experiment
from qeccal.guarantees import cp_lower, learn_then_test, loosest_where, thresholds
from qeccal.soft.cache import cache_path, load

REPO = pathlib.Path(__file__).resolve().parents[1]
RES = REPO / "results"
ALPHAS = (1e-3, 3e-3, 1e-2, 3e-2, 1e-1)
DELTA = 0.05
COMBOS = [("mwpm_gap", "rl"), ("bm_gap", "rl"), ("nn", "rl")]
GRIDS = {step: np.round(np.arange(step, 1.0001, step), 2) for step in (0.05, 0.02, 0.01)}
FIELDS = ["key", "distance", "patch", "basis", "rounds", "method", "prior", "grid_step", "alpha", "rule", "keep",
          "cal_n", "cal_errors", "test_n", "test_size", "test_errors", "exceed", "sig_exceed"]


def run(key):
    e = get_experiment(key)
    idx = split_indices(e)
    obs = e.observable_flips()
    base = {"key": key, "distance": e.distance, "patch": e.patch, "basis": e.basis, "rounds": e.rounds}
    rows = []
    for method, prior in COMBOS:
        if not cache_path(method, prior, key).exists():
            continue
        o = load(method, prior, key)
        s = o["gap"].astype(np.float64) if "gap" in o else score_from_q(o["q"])
        wrong = o["pred"] != obs
        tr, ca, te = idx["train"], idx["calibrate"], idx["test"]
        if "fit_mask" in o:                                # learned decoder: drop the Train shots it was trained on
            tr = tr[~o["fit_mask"][tr]]
        s_ca, w_ca, s_te, w_te = s[ca], wrong[ca], s[te], wrong[te]
        for step, grid in GRIDS.items():
            lams = thresholds(s[tr], grid)
            kept_ca = [s_ca >= lam for lam in lams]
            cal_err = [w_ca[k].mean() if k.any() else np.inf for k in kept_ca]
            for alpha in ALPHAS:
                choice = {"ltt": learn_then_test(s_ca, w_ca, lams, alpha, DELTA, grid)[0],
                          "plugin": loosest_where(cal_err, lambda v: v <= alpha)}
                for rule, i in choice.items():
                    row = {**base, "method": method, "prior": prior, "grid_step": step, "alpha": alpha,
                           "rule": rule, "test_size": te.size}
                    if i is None:
                        rows.append({**row, "keep": "", "cal_n": "", "cal_errors": "", "test_n": "",
                                     "test_errors": "", "exceed": "", "sig_exceed": ""})
                        continue
                    kt = s_te >= lams[i]
                    n, er = int(kt.sum()), int(w_te[kt].sum())
                    rows.append({**row, "keep": grid[i], "cal_n": int(kept_ca[i].sum()),
                                 "cal_errors": int(w_ca[kept_ca[i]].sum()), "test_n": n, "test_errors": er,
                                 "exceed": int(n > 0 and er / n > alpha), "sig_exceed": int(cp_lower(er, n) > alpha)})
    return rows


def summarise(rows):
    name = {"mwpm_gap": "MWPM gap", "bm_gap": "belief-matching gap", "nn": "learned decoder"}
    L = ["# Learn-then-Test: sensitivity to the threshold grid (generated by scripts/m4_grid_sensitivity.py)", "",
         "Same frozen scores, splits and delta = 0.05 as results/m4_guarantees.csv; only the grid of Train keep "
         "fractions changes. Kept = fraction of Test shots kept. 'Both select' = experiments where Learn-then-Test "
         "certifies and the plug-in rule selects; price = plug-in kept minus Learn-then-Test kept on those, in "
         "percentage points. Exceeds / significant: over certified experiments (significant = one-sided 95% "
         "Clopper-Pearson lower bound on Test error above alpha).", ""]
    for method, prior in COMBOS:
        sub = [r for r in rows if r["method"] == method and r["prior"] == prior]
        if not sub:
            continue
        n_exp = len({r["key"] for r in sub})
        L += [f"## {name[method]}, {prior.upper()} prior ({n_exp} experiments)", "",
              "| alpha | grid step | LTT certified | LTT exceeds | LTT significant | LTT kept (uncertified = 0) | "
              "both select | kept, LTT | kept, plug-in | price (pp) |", "|---|---|---|---|---|---|---|---|---|---|"]
        for alpha in ALPHAS:
            for step in GRIDS:
                g = [r for r in sub if r["alpha"] == alpha and r["grid_step"] == step]
                ltt = {r["key"]: r for r in g if r["rule"] == "ltt"}
                plug = {r["key"]: r for r in g if r["rule"] == "plugin"}
                cert = [r for r in ltt.values() if r["keep"] != ""]
                frac = lambda r: r["test_n"] / r["test_size"]
                kept0 = np.mean([frac(r) if r["keep"] != "" else 0.0 for r in ltt.values()])
                both = sorted(k for k in ltt if ltt[k]["keep"] != "" and plug[k]["keep"] != "")
                kl = np.mean([frac(ltt[k]) for k in both]) if both else np.nan
                kp = np.mean([frac(plug[k]) for k in both]) if both else np.nan
                ex = np.mean([r["exceed"] for r in cert]) if cert else np.nan
                sg = np.mean([r["sig_exceed"] for r in cert]) if cert else np.nan
                L.append(f"| {alpha:g} | {100 * step:.0f}% | {len(cert)}/{len(ltt)} | {100 * ex:.1f}% | "
                         f"{100 * sg:.1f}% | {kept0:.3f} | {len(both)} | {kl:.3f} | {kp:.3f} | {100 * (kp - kl):.1f} |")
        g = [r for r in sub if r["alpha"] == 1e-2 and r["rule"] == "ltt" and r["distance"] == 3 and r["rounds"] == 10]
        if g:
            L += ["", "d = 3, r = 10, alpha = 1e-2, Learn-then-Test: mean fraction of Test shots kept over certified "
                  "experiments: " + ", ".join(
                      f"{100 * s:.0f}% grid {np.mean([r['test_n'] / r['test_size'] for r in g if r['grid_step'] == s and r['keep'] != '']):.3f}"
                      f" ({sum(1 for r in g if r['grid_step'] == s and r['keep'] != '')} certified)" for s in GRIDS)]
        L.append("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--summary-only", action="store_true", help="rebuild the .md from an existing .csv")
    args = ap.parse_args()
    out_csv, out_md = RES / "m4_grid_sensitivity.csv", RES / "m4_grid_sensitivity.md"
    if not args.summary_only:
        keys = [e.key for e in list_experiments() if "test" in split_indices(e)]
        t0 = time.time()
        with cf.ProcessPoolExecutor(max_workers=args.workers) as pool:
            results = dict(zip(keys, pool.map(run, keys, chunksize=4)))
        with out_csv.open("w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=FIELDS)
            w.writeheader()
            for key in keys:                                   # deterministic row order
                w.writerows(results[key])
        print(f"done in {time.time() - t0:.0f}s: {len(keys)} experiments -> {out_csv.name}")
    rows = []
    with out_csv.open() as f:
        for r in csv.DictReader(f):
            for k in ("distance", "rounds", "test_size"):
                r[k] = int(r[k])
            for k in ("grid_step", "alpha"):
                r[k] = float(r[k])
            if r["keep"] != "":
                for k in ("test_n", "test_errors", "exceed", "sig_exceed"):
                    r[k] = int(r[k])
            rows.append(r)
    out_md.write_text(summarise(rows))
    print(f"-> {out_md.name}")


if __name__ == "__main__":
    main()
